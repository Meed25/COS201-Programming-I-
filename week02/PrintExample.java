public class PrintExample {
    public static void main(String[] args) {

        System.out.println("Demonstration of print() and println():");
        System.out.println("----------------------------------------");

        // print() continues displaying text on the same line.
        System.out.print("COS ");
        System.out.print("201");

        // println() moves the output to the next line.
        System.out.println();

        // Each println() statement displays text on a new line.
        System.out.println("Java");
        System.out.println("Cybersecurity");
        System.out.println("Student: Adesanya hameed");
        System.out.println("Matric Number: 25/16540");
    }
}
